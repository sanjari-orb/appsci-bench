"""One table across every task: does the agent's own eval track the real one, build by build?

Reads the `self_grade_vs_real/stats.json` that `internal_vs_external.py` writes for each task under
`results/<model>/`, and writes `SUMMARY.md` and `summary.csv` beside them. Nothing is re-measured; this
only gathers numbers already committed, so the figures quoted in a paper can be regenerated from the
repository rather than from someone's notebook.

THE UNIT IS THE BUILD. Each build writes its own internal exam, so internal levels do not compare across
builds and a pooled correlation would put several different rulers on one axis. Every average here is
therefore an average of per-build statistics, never a statistic computed over pooled points.

A build whose tau-b is undefined -- one distinct program, or a flat axis -- is listed but left out of the
tau-b averages, and the count of builds that went into each average is printed beside it. Dropping
those silently would make the average look better supported than it is.

    python scripts/analysis/internal_eval_consistency/summarize_results.py [--model claude-opus-4-8]
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import pathlib
import statistics
import sys

RESULTS = pathlib.Path(__file__).resolve().parent / "results"

COLUMNS = [
    "task", "build", "programs", "deploys", "kendall_tau_b", "spearman", "pearson",
    "internal_first", "internal_last", "external_first", "external_last", "external_noise_sd",
    "regret", "loop_correct", "loop_wrong",
]


def _num(value) -> float:
    """A stats.json number, or nan. JSON has no nan, so the writer may have left None or a string."""
    try:
        out = float(value)
    except (TypeError, ValueError):
        return math.nan
    return out


def _build(run_id: str) -> str:
    """`..._b0_l3_20260920_174913` -> `b0 (0920)`: the index alone is not unique across launches."""
    parts = run_id.split("_")
    index = next((p for p in parts if len(p) == 2 and p[0] == "b" and p[1].isdigit()), run_id)
    date = next((p for p in parts if len(p) == 8 and p.isdigit()), "")
    return f"{index} ({date[4:]})" if date else index


def rows_for(model_dir: pathlib.Path) -> tuple[list[dict], dict[str, dict]]:
    """(one row per build, {task: skipped-builds map}) for every task that has a stats file."""
    rows, skipped = [], {}
    for stats_path in sorted(model_dir.glob("*/self_grade_vs_real/stats.json")):
        task = stats_path.parents[1].name
        data = json.loads(stats_path.read_text())
        if data.get("skipped"):
            skipped[task] = data["skipped"]
        for run_id, s in sorted((data.get("series") or {}).items()):
            regret = s.get("regret")
            rows.append({
                "task": task,
                "build": _build(run_id),
                "programs": s.get("programs_built", s.get("n")),
                "deploys": s.get("n_deploys"),
                "kendall_tau_b": _num(s.get("kendall_tau_b")),
                "spearman": _num(s.get("spearman")),
                "pearson": _num(s.get("pearson")),
                "internal_first": _num(s.get("internal_first")),
                "internal_last": _num(s.get("internal_last")),
                "external_first": _num(s.get("external_first")),
                "external_last": _num(s.get("external_last")),
                "external_noise_sd": _num(s.get("external_noise_sd")),
                "regret": _num(regret.get("regret")) if isinstance(regret, dict) else math.nan,
                "loop_correct": (s.get("loop_correct_keep") or 0) + (s.get("loop_correct_reject") or 0),
                "loop_wrong": (s.get("loop_wrong_keep") or 0) + (s.get("loop_wrong_reject") or 0),
            })
    return rows, skipped


def _mean(values: list[float]) -> tuple[float, int]:
    finite = [v for v in values if not math.isnan(v)]
    return (statistics.mean(finite) if finite else math.nan), len(finite)


def _fmt(value: float, spec: str = "+.2f") -> str:
    return "n/a" if math.isnan(value) else format(value, spec)


def render(model: str, rows: list[dict], skipped: dict[str, dict]) -> str:
    tasks = sorted({r["task"] for r in rows})
    out = [f"# Internal vs external eval: {model}", "",
           "Generated by `summarize_results.py` from each task's `self_grade_vs_real/stats.json`. "
           "Every average is over per-build statistics; see the script's docstring for why nothing "
           "is pooled.", "", "## Per build", "",
           "| task | build | programs | τb | Spearman | Pearson | internal first→last "
           "| external first→last | noise sd | regret | loop right / wrong |",
           "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(
            f"| {r['task']} | {r['build']} | {r['programs']} | {_fmt(r['kendall_tau_b'])} "
            f"| {_fmt(r['spearman'])} | {_fmt(r['pearson'])} "
            f"| {_fmt(r['internal_first'], '.3f')}→{_fmt(r['internal_last'], '.3f')} "
            f"| {_fmt(r['external_first'], '.3f')}→{_fmt(r['external_last'], '.3f')} "
            f"| {_fmt(r['external_noise_sd'], '.4f')} | {_fmt(r['regret'], '.3f')} "
            f"| {r['loop_correct']} / {r['loop_wrong']} |")

    out += ["", "## Per task", "",
            "| task | builds | mean τb (n) | mean regret | loop decisions right |",
            "|---|---|---|---|---|"]
    task_means = []
    for task in tasks:
        tr = [r for r in rows if r["task"] == task]
        tau, n_tau = _mean([r["kendall_tau_b"] for r in tr])
        reg, _ = _mean([r["regret"] for r in tr])
        right = sum(r["loop_correct"] for r in tr)
        total = right + sum(r["loop_wrong"] for r in tr)
        share = f"{100 * right / total:.0f}% of {total}" if total else "n/a"
        task_means.append(tau)
        out.append(f"| {task} | {len(tr)} | {_fmt(tau)} ({n_tau}) | {_fmt(reg, '.3f')} | {share} |")

    tau_builds, n_builds = _mean([r["kendall_tau_b"] for r in rows])
    tau_tasks, n_tasks = _mean(task_means)
    positive = [r for r in rows if not math.isnan(r["kendall_tau_b"])]
    share_pos = (100 * sum(r["kendall_tau_b"] > 0 for r in positive) / len(positive)) if positive else math.nan
    right = sum(r["loop_correct"] for r in rows)
    total = right + sum(r["loop_wrong"] for r in rows)
    zero_regret = [r for r in rows if not math.isnan(r["regret"])]
    out += ["", "## Across tasks", "",
            f"- mean τb over builds: **{_fmt(tau_builds)}** ({n_builds} builds with a defined τb)",
            f"- mean τb over task means: **{_fmt(tau_tasks)}** ({n_tasks} tasks), which weights each task "
            "equally however many builds it has",
            f"- builds with τb > 0: **{_fmt(share_pos, '.0f')}%** of {len(positive)}",
            f"- loop accept/reject decisions the external eval agreed with: "
            f"**{(f'{100 * right / total:.0f}%' if total else 'n/a')}** of {total}",
            f"- builds that shipped their best program (regret 0): "
            f"**{(f'{100 * sum(r['regret'] == 0 for r in zero_regret) / len(zero_regret):.0f}%' if zero_regret else 'n/a')}** "
            f"of {len(zero_regret)}"]
    if skipped:
        out += ["", "## Builds not in these numbers", ""]
        for task, reasons in sorted(skipped.items()):
            for reason, names in sorted(reasons.items()):
                out.append(f"- {task}: {len(names)} build(s) skipped, `{reason}`")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--model", default="claude-opus-4-8", help="Directory under results/.")
    args = parser.parse_args(argv)

    model_dir = RESULTS / args.model
    if not model_dir.is_dir():
        print(f"no results for {args.model} under {RESULTS}", file=sys.stderr)
        return 1
    rows, skipped = rows_for(model_dir)
    if not rows:
        print(f"no self_grade_vs_real/stats.json under {model_dir}", file=sys.stderr)
        return 1

    (model_dir / "SUMMARY.md").write_text(render(args.model, rows, skipped))
    with (model_dir / "summary.csv").open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote SUMMARY.md and summary.csv for {len(rows)} builds across "
          f"{len({r['task'] for r in rows})} tasks to {model_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
